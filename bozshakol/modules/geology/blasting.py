"""Буровзрывные работы: проект взрыва, модель Кузнецова–Рамлера, скорость бурения и MWD.

Все формулы — честные, без подгонки под результат. Проектные параметры (диаметр скважины,
сетка, забойка, ВВ) — наши решения, их обоснование — в README модуля.
"""
import math

# --- проект буровзрывных работ (наше проектное решение) ---------------------------------
HOLE_D_MM = 251.0        # диаметр скважины, мм
BURDEN_M = 8.0           # B — сопротивление по подошве, м
SPACING_M = 9.0          # S — расстояние между скважинами, м
BENCH_H_M = 15.0         # H — высота уступа, м
SUBDRILL_M = 2.0         # перебур, м
HOLE_DEPTH_M = BENCH_H_M + SUBDRILL_M   # глубина скважины 17 м
STEMMING_M = 6.0         # забойка, м
ANFO_DENSITY = 850.0     # плотность ANFO в скважине, кг/м³
ANFO_E = 100.0           # относительная работоспособность ВВ (ANFO = 100)
DEVIATION_M = 0.3        # W — отклонение скважины при бурении, м (принято)

# --- коэффициент породы A (Кузнецов): линейно по крепости Протодьяконова, с ограничением ------
A_AT_F4, A_AT_F16 = 7.0, 13.0
A_MIN, A_MAX = 7.0, 13.0
A_SHIFT = 0.0            # сдвиг A по данным El Aljibe (не определён: в наборе нет параметров взрыва)

# --- скорость бурения: крепче — медленнее (допущение, степенная зависимость ROP ~ f^-k) ------
ROP_F5, ROP_F16 = 40.0, 15.0                        # м/ч при f = 5 и f = 16
ROP_K = math.log(ROP_F16 / ROP_F5) / math.log(16.0 / 5.0)    # показатель степени (< 0)
F_REF = 12.0             # крепость «обычной» сульфидной руды, опорная для P80_REF

LF_MIN, LF_MAX = 0.5, 1.2   # границы коэффициента скорости погрузки


def holes_per_block(block_xy):
    """Скважин на блок: площадь блока в плане / площадь сетки (округление до целого)."""
    return max(1, round(block_xy * block_xy / (BURDEN_M * SPACING_M)))


def charge():
    """Заряд одной скважины из геометрии: длина заряда, масса ВВ, объём породы, удельный расход."""
    length = HOLE_DEPTH_M - STEMMING_M
    mass = ANFO_DENSITY * math.pi * (HOLE_D_MM / 1000.0) ** 2 / 4.0 * length   # кг
    volume = BURDEN_M * SPACING_M * BENCH_H_M                                   # м³ на скважину
    return {"length": length, "mass": mass, "volume": volume, "powder_factor": mass / volume}


def rock_factor_A(f):
    """Коэффициент породы A: 7 при f = 4 до 13 при f = 16, линейно, с ограничением; плюс сдвиг A_SHIFT."""
    a = A_AT_F4 + (f - 4.0) * (A_AT_F16 - A_AT_F4) / 12.0
    return min(A_MAX, max(A_MIN, a)) + A_SHIFT


def uniformity_n():
    """Индекс однородности Каннингема n = (2,2 − 14·B/d)·√((1+S/B)/2)·(1 − W/B)·(L/H)."""
    c = charge()
    b, s = BURDEN_M, SPACING_M
    return (2.2 - 14.0 * b / HOLE_D_MM) * math.sqrt((1.0 + s / b) / 2.0) * (1.0 - DEVIATION_M / b) * (c["length"] / BENCH_H_M)


def fragmentation(f):
    """Модель Кузнецова–Рамлера: X50 (см), индекс n, характерный размер Xc (см) и P80 (мм) по крепости f."""
    c = charge()
    a = rock_factor_A(f)
    x50 = a * (c["volume"] / c["mass"]) ** 0.8 * c["mass"] ** (1.0 / 6.0) * (115.0 / ANFO_E) ** (19.0 / 30.0)
    n = uniformity_n()
    xc = x50 / 0.693 ** (1.0 / n)
    p80 = xc * math.log(5.0) ** (1.0 / n) * 10.0
    return {"A": a, "x50_cm": x50, "n": n, "xc_cm": xc, "p80_mm": p80}


def p80_mm(f):
    return fragmentation(f)["p80_mm"]


P80_REF = p80_mm(F_REF)   # крупность при обычном взрыве (сульфидная руда, f = 12), мм


def loading_factor(p80):
    """Чем крупнее кусок, тем медленнее погрузка: ограничить((P80_ref / P80)^0,5; 0,5 … 1,2) — допущение."""
    return min(LF_MAX, max(LF_MIN, (P80_REF / max(p80, 1.0)) ** 0.5))


# --- бурение и MWD --------------------------------------------------------------------
def rop_from_hardness(f):
    """Механическая скорость бурения, м/ч, по крепости (40 м/ч при f = 5, 15 м/ч при f = 16)."""
    return ROP_F5 * (max(f, 1.0) / 5.0) ** ROP_K


def hardness_from_rop(rop):
    """MWD: крепость по скорости бурения — обратная формула (станок крепость не знает, а измеряет)."""
    return 5.0 * (ROP_F5 / max(rop, 0.5)) ** (1.0 / -ROP_K)
