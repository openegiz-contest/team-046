"""Энергопотребление фабрик Бозшаколя: мощность каждого потребителя по его состоянию.

Все мощности — в кВт. x — загрузка агрегата: питание ÷ план (0 — крутится без руды, 1 — плановое питание).
Источники и допущения — в README.md модуля (раздел «Энергетика»). Простые линейные модели:
P = P_холостого_хода + (P_под_нагрузкой − P_холостого_хода) × x; стоит или в ремонте — 0.
"""
G = 9.81

# -- мельницы (ABB, automation.com): безредукторные приводы ---------------------------------------
SAG_INSTALLED_KW = 28000.0          # мельница ПСИ 12,2 м, 28 МВт
BALL_INSTALLED_KW = 2 * 22000.0     # две шаровые 8,5 м по 22 МВт
MILL_LOAD = 0.90   # доля установленной мощности при плановом питании (допущение: обычно 85–90 %; фабрика работает выше проектной)
MILL_IDLE = 0.35   # мельница крутится без руды (допущение: мощность на вращение пустого барабана и шаров)
MILL_X_MAX = 1.15  # больше 115 % плана мельница не берёт

# -- дробление и конвейер ---------------------------------------------------------------------------
CRUSHER_RATED_KW = 750.0   # гирационная дробилка 60-89 (допущение: двигатель ≈ 750 кВт)
CRUSHER_IDLE_KW = 225.0    # холостой ход — 30 % (допущение)
PEBBLE_KW = (100.0, 350.0)  # дробилка гали (конусная): холостой ход / при плановом питании (допущение)
BELT_F = 0.025             # фиктивный коэффициент сопротивления движению ленты (типично 0,02–0,03)
BELT_MOVING_KG_M = 80.0    # масса движущихся частей на метр: лента 1,6 м (обе ветви) + ролики (допущение)
BELT_ETA = 0.9             # КПД привода (допущение)

# -- прочие потребители сульфидной фабрики: (холостой ход, при плановом питании), кВт -------------------
SULPH_OTHER = {
    "flotation": (2000.0, 5000.0),   # флотомашины и воздуходувки (допущение)
    "regrind": (1500.0, 4000.0),     # доизмельчение концентрата (допущение)
    "pumps": (3000.0, 9000.0),       # пульповые и водяные насосы, насосы гидроциклонов, оборотная вода (допущение)
    "thickeners": (800.0, 1500.0),   # сгустители и фильтры концентрата и хвостов (допущение)
}
AUX_KW = 4000.0          # вспомогательные нужды: освещение, сжатый воздух, водоснабжение, мастерские (допущение)

# -- фабрика глинистой руды ---------------------------------------------------------------------------
CLAY_KW = (3200.0, 10700.0)   # своя линия: ≈ 15 кВт·ч/т при 715 т/ч, холостой ход 30 % (допущение)

# -- отопление и вентиляция (Ausenco: корпуса отапливаемые, зима до −40 °C) ------------------------------
HEAT_INSIDE_C = 18.0     # температура в корпусах
HEAT_W_M3K = 0.12        # удельные теплопотери, Вт/(м³·К) (допущение: утеплённые корпуса, часть тепла дают мельницы)
VENT_KW = 800.0          # вентиляция, круглый год (допущение)


def mill_kw(installed, x, running):
    """Мельница: 0 — стоит/ремонт; иначе от 35 % (без руды) до 88 % (плановое питание) установленной."""
    if not running:
        return 0.0
    return installed * (MILL_IDLE + (MILL_LOAD - MILL_IDLE) * min(max(x, 0.0), MILL_X_MAX))


def linear_kw(pair, x, running):
    idle, plan = pair
    return 0.0 if not running else idle + (plan - idle) * min(max(x, 0.0), MILL_X_MAX)


def crusher_kw(tph, rated_tph, state):
    if state == "running":
        return CRUSHER_IDLE_KW + (CRUSHER_RATED_KW - CRUSHER_IDLE_KW) * min(tph / rated_tph, 1.15)
    return CRUSHER_IDLE_KW if state == "idle" else 0.0


def conveyor_kw(tph, length_m, lift_m, speed_mps, running):
    """Ленточный конвейер: подъём руды + сопротивление движению (руда и лента), ÷ КПД привода.
    Возвращает (мощность, мощность холостого хода) в кВт."""
    if not running:
        return 0.0, 0.0
    q = tph / 3.6                                          # кг/с руды
    empty = BELT_F * G * length_m * BELT_MOVING_KG_M * speed_mps / 1000.0
    load = (q * G * lift_m + BELT_F * G * length_m * q) / 1000.0
    return (empty + max(0.0, load)) / BELT_ETA, empty / BELT_ETA


def heating_kw(volume_m3, temp_c):
    """Отопление корпуса: теплопотери ∝ объём × (18 °C − наружная), при тёплой погоде — 0."""
    return HEAT_W_M3K * volume_m3 * max(0.0, HEAT_INSIDE_C - temp_c) / 1000.0


def sulphide_kw(x, mills_running, others_running):
    """Мельницы и прочие агрегаты сульфидной фабрики при загрузке x (без дробления, конвейера и отопления)."""
    sag = mill_kw(SAG_INSTALLED_KW, x, mills_running)
    ball = mill_kw(BALL_INSTALLED_KW, x, mills_running)
    other = {k: linear_kw(v, x, others_running) for k, v in SULPH_OTHER.items()}
    return sag, ball, other


def limit_feed_fraction(limit_kw, rest_kw, mills_running):
    """Какую долю плана может взять сульфидная фабрика, чтобы общая мощность была не выше предела.
    rest_kw — всё, что от питания мельниц не зависит (дробление, конвейер, глина, отопление, вспомогательные)."""
    def total(x):
        sag, ball, other = sulphide_kw(x, mills_running, True)
        return rest_kw + sag + ball + sum(other.values()) + linear_kw(PEBBLE_KW, x, True)
    p0, p1 = total(0.0), total(1.0)
    if p1 <= limit_kw:
        return 1.0
    if p0 >= limit_kw or p1 <= p0:
        return 0.0
    return (limit_kw - p0) / (p1 - p0)
